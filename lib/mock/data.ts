export function getService(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug);
}

export function getOrder(code: string): Order | undefined {
  return orders.find((o) => o.code.toUpperCase() === code.toUpperCase());
}

export function getCreator(handle: string): Creator | undefined {
  return handle.replace(/^@/, "").toLowerCase() === creator.handle ? creator : undefined;
}
