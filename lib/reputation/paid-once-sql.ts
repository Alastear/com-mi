import { sql } from "drizzle-orm";

/**
 * "ร้านเคยยืนยันรับเงินของออเดอร์นี้" — ใช้เป็นเงื่อนไขเงินของประวัติร้านและรีวิวทุกจุด
 *
 * ⚠️ ต้องอ้างถึงออเดอร์ด้วย alias `o` เสมอ (`from "order" o`) — fragment นี้ผูกกับชื่อนั้น
 *
 * ⚠️ **ไม่กรอง `voided_at`** โดยตั้งใจ: แถวที่ถูกยกเลิกการยืนยันยังมี `verified_at` เก็บไว้เป็นหลักฐาน
 * (ดู schema ของ `payment_record`) เดิมใช้ `amount_paid_cents > 0` ณ ตอนอ่าน ซึ่งร้านกดลดให้เป็นศูนย์ได้เอง
 * ด้วย `voidPayment` ทุกสถานะที่รับเงิน รวม `completed` — ผลคือรีวิวดาวเดียวหายจากหน้าร้าน
 * งานที่ส่งช้าหลุดจากตัวหาร และ "ยกเลิกหลังรับเงิน" หายไปจากตัวเลข โดยลูกค้าไม่รู้ตัว
 * การยืนยันที่เกิดขึ้นแล้วเป็นข้อเท็จจริงที่ย้อนไม่ได้ ตัวเลขจึงต้องไม่ขยับตามปุ่มของร้าน
 *
 * แถวที่ถูกปฏิเสธมี `verified_at` เป็น null เสมอ (ปฏิเสธได้เฉพาะแถวที่ยังไม่ยืนยัน) จึงไม่หลุดเข้ามา
 * ใช้ `payment_order_idx` (order_id, created_at) — ออเดอร์หนึ่งใบมีแถวเงินไม่กี่แถว
 *
 * ต้องตรงกับ `paidOnce()` ใน review-rules.ts (หน้าจอใช้ตัดสินว่าจะโชว์ฟอร์มรีวิวไหม)
 */
export const PAID_ONCE_SQL = sql`exists (
  select 1 from payment_record pv
  where pv.order_id = o.id and pv.verified_at is not null
)`;
