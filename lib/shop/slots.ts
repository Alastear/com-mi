import type { ShopStatus } from "@/lib/types";

/**
 * จำนวนช่องที่จะโชว์บนหน้าร้าน หรือ `null` = ไม่ต้องโชว์บรรทัดนี้
 *
 * `slotsTotal` คือตัวเลขที่ครีเอเตอร์ **ประกาศเอง** ในหน้าจัดการร้าน ไม่ใช่ยอดที่ระบบนับ
 * ไม่มีอะไรหักมันเมื่อมีงานเข้า — เดิมหน้าร้านเขียนว่า "เหลืออีก n คิว" จากค่านี้ตรง ๆ
 * ส่วนหน้าแก้ไขเรียกช่องเดียวกันว่า "คิวปัจจุบัน" สองหน้าจึงพูดคนละเรื่องด้วยตัวเลขเดียว
 * และไม่มีเรื่องไหนจริง ตอนนี้ทั้งสองฝั่งเรียกว่า "ช่องที่เปิดรับ" เหมือนกัน
 *
 * ⚠️ โชว์เฉพาะตอนสถานะ "เปิดรับงาน" — ร้านที่ปิด พัก หรือเปิดแค่รายชื่อรอ
 * ถ้ายังขึ้นว่า "เปิดรับ 5 ช่อง" คู่กับป้าย "ปิดรับงาน" คนอ่านจะไม่รู้ว่าเชื่ออันไหน
 */
export function openSlotsToShow(status: ShopStatus, slotsTotal: number): number | null {
  if (status !== "open") return null;
  if (!Number.isInteger(slotsTotal) || slotsTotal <= 0) return null;
  return slotsTotal;
}
